"""The downloadable study pack.

The pack is rendered as a print-designed HTML document and converted to PDF by
the headless browser already present on the machine (Chrome or Edge).

Why a browser rather than a PDF library: Hindi and Bangla need complex-script
shaping — reordered matras, conjuncts, ligatures. A text-drawing PDF library
places glyphs in code-point order and produces subtly wrong Devanagari. The
browser uses HarfBuzz and gets it right, which matters when the entire point of
the product is that a student can study in their own language.

If no browser is found the HTML is returned instead, which the student can still
read and print. Nothing here costs money or leaves the machine.
"""

