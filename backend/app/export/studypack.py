def find_browser() -> str | None:
    for candidate in BROWSERS:
        if Path(candidate).exists():
            return candidate
    for name in ("chrome", "msedge", "chromium", "google-chrome"):
        found = shutil.which(name)
        if found:
            return found
    return None


def html_to_pdf(html_text: str, out_path: Path, timeout: int = 90) -> bool:
    """Convert with the local headless browser. Returns False if unavailable."""
    browser = find_browser()
    if not browser:
        log.warning("no Chrome/Edge found; cannot render PDF")
        return False

    with tempfile.TemporaryDirectory(prefix="luminara-pdf-") as tmp:
        source = Path(tmp) / "studypack.html"
        source.write_text(html_text, encoding="utf-8")
        profile = Path(tmp) / "profile"

        base_args = [
            browser,
            "--disable-gpu",
            "--no-sandbox",
            "--no-first-run",
            "--no-default-browser-check",
            "--disable-extensions",
            f"--user-data-dir={profile}",
            "--no-pdf-header-footer",
            "--run-all-compositor-stages-before-draw",
            "--virtual-time-budget=8000",
            f"--print-to-pdf={out_path}",
            source.as_uri(),
        ]

        for headless in ("--headless=new", "--headless"):
            args = [base_args[0], headless] + base_args[1:]
            try:
                result = subprocess.run(args, capture_output=True, timeout=timeout)
            except subprocess.TimeoutExpired:
                log.warning("headless print timed out with %s", headless)
                continue
            if out_path.exists() and out_path.stat().st_size > 1024:
                return True
            log.warning(
                "headless print produced nothing with %s: %s",
                headless,
                (result.stderr or b"").decode("utf-8", "ignore")[:300],
            )
    return False
