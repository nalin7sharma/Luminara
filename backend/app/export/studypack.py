def _e(value) -> str:
    return html.escape(str(value or ""))


def _chips(sources: list[dict]) -> str:
    if not sources:
        return ""
    out = []
    for source in sources[:4]:
        kind = str(source.get("type", "")).lower()
        cls = "speech" if kind == "speech" else "formula" if kind == "formula" else "board"
        label = kind.replace("_", " ").title()
        ref = source.get("ref", "")
        text = f"{label} · {ref}" if ref and ref.lower() != kind else label
        out.append(f'<span class="chip {cls}">{_e(text)}</span>')
    return f'<div class="src">{"".join(out)}</div>'


def render_html(
    knowledge: dict,
    script_doc: dict,
    *,
    language: str = "en",
    course: str = "",
    engines: dict | None = None,
    board_image: Path | None = None,
    board_text: str = "",
) -> str:
    t = LANGUAGE_HEADINGS.get(language, LANGUAGE_HEADINGS["en"])
    rtl = language == "ar"
    parts: list[str] = []

    # ---- cover -----------------------------------------------------------
    pills = [t["pack"], datetime.now(timezone.utc).strftime("%d %b %Y")]
    if script_doc.get("duration_sec"):
        pills.append(f"{int(script_doc['duration_sec'])}s")
    if knowledge.get("formulas"):
        pills.append(f"{len(knowledge['formulas'])} × {t['formulas']}")
    parts.append(
        f"""
<div class="cover">
  <div class="mark"><div class="dot"></div><div class="brand">LUMINARA</div></div>
  <div class="kicker">{_e(t['pack'])}</div>
  <h1>{_e(knowledge.get('title', 'Lecture'))}</h1>
  <div class="course">{_e(course)}</div>
  <div class="meta">{''.join(f'<span class="pill">{_e(p)}</span>' for p in pills)}</div>
</div>"""
    )

    if knowledge.get("summary"):
        parts.append(
            f"<section><h2>{_e(t['summary'])}</h2><p>{_e(knowledge['summary'])}</p></section>"
        )

    if knowledge.get("key_concepts"):
        blocks = "".join(
            f'<div class="concept"><h3>{_e(c.get("name"))}</h3>'
            f'<p>{_e(c.get("explanation"))}</p>{_chips(c.get("sources") or [])}</div>'
            for c in knowledge["key_concepts"]
        )
        parts.append(f"<section><h2>{_e(t['concepts'])}</h2>{blocks}</section>")

    if knowledge.get("important_points"):
        items = "".join(
            f'<li>{_e(p.get("text"))}{_chips(p.get("sources") or [])}</li>'
            for p in knowledge["important_points"]
        )
        parts.append(f"<section><h2>{_e(t['points'])}</h2><ul>{items}</ul></section>")

    if knowledge.get("formulas"):
        blocks = "".join(
            f'<div class="formula-card"><div class="expr">{_e(f.get("plain") or f.get("latex"))}</div>'
            f'<div class="meaning">{_e(f.get("meaning"))}</div>'
            f'{_chips([{"type": "formula", "ref": f.get("source_ref", "Whiteboard")}])}</div>'
            for f in knowledge["formulas"]
        )
        parts.append(f"<section><h2>{_e(t['formulas'])}</h2>{blocks}</section>")

    visuals = knowledge.get("visual_explanations") or []
    if visuals or board_image or board_text:
        inner = ""
        if board_image and board_image.exists():
            try:
                data = base64.b64encode(board_image.read_bytes()).decode("ascii")
                mime = "image/png" if board_image.suffix.lower() == ".png" else "image/jpeg"
                inner += f'<img class="board-img" src="data:{mime};base64,{data}" />'
            except Exception as exc:
                log.warning("could not embed board image: %s", exc)
        for visual in visuals:
            inner += (
                f'<div class="concept"><h3>{_e(visual.get("title"))}</h3>'
                f'<p>{_e(visual.get("explanation"))}</p>'
                f'{_chips([{"type": "diagram", "ref": visual.get("source_ref", "Whiteboard")}])}</div>'
            )
        if board_text:
            inner += f'<div class="boardtext">{_e(board_text)}</div>'
        parts.append(f"<section><h2>{_e(t['visuals'])}</h2>{inner}</section>")

    if knowledge.get("technical_terms"):
        rows = "".join(
            f'<tr><td class="t">{_e(term.get("term"))}</td>'
            f'<td>{_e(term.get("definition"))}</td></tr>'
            for term in knowledge["technical_terms"]
        )
        parts.append(
            f"<section><h2>{_e(t['terms'])}</h2><table class=\"terms\">{rows}</table></section>"
        )

    if knowledge.get("simple_explanation"):
        parts.append(
            f"<section><h2>{_e(t['simple'])}</h2>"
            f'<div class="simple">{_e(knowledge["simple_explanation"])}</div></section>'
        )

    # ---- script ----------------------------------------------------------
    if script_doc.get("entries"):
        lines = ""
        for entry in script_doc["entries"]:
            marker = ""
            board = [r for r in entry.get("related", []) if r.get("kind") == "board"]
            if board:
                marker = (
                    f'<div class="marker">↳ {_e(t["board_only"])}: '
                    f'{_e(board[0].get("detail") or board[0].get("label"))}</div>'
                )
            lines += (
                f'<div class="line"><div class="tc">{_e(entry["timecode"])}</div>'
                f'<div class="txt">{_e(entry["text"])}{marker}</div></div>'
            )
        parts.append(f'<section class="script"><h2>{_e(t["script"])}</h2>{lines}</section>')

    if script_doc.get("board_only"):
        items = "".join(
            f'<li><strong>{_e(b.get("label"))}</strong> — {_e(b.get("detail"))}</li>'
            for b in script_doc["board_only"]
        )
        parts.append(f"<section><h2>{_e(t['board_only'])}</h2><ul>{items}</ul></section>")

    engine_line = ""
    if engines:
        engine_line = " · ".join(f"{k}: {v}" for k, v in engines.items() if v)

    parts.append(
        f"""<footer>{_e(t['generated'])} — {_e(engine_line)}<br>
Formulas and technical terms are reproduced exactly as they appeared in the lecture
and are never translated.</footer>"""
    )

    direction = ' dir="rtl"' if rtl else ""
    return f"""<!DOCTYPE html>
<html lang="{_e(language)}"{direction}>
<head><meta charset="utf-8"><title>{_e(knowledge.get('title', 'Lecture'))} — Luminara</title>
<style>{CSS}</style></head>
<body>{''.join(parts)}</body></html>"""


